std::string iso639Alpha2(std::string_view text)
{
    std::string folded;
    folded.reserve(text.size());
    for (const char c : text) {
        folded.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(c))));
    }

    const auto found = std::lower_bound(
        std::begin(kNames), std::end(kNames), folded,
        [](const auto &row, const std::string &wanted) { return row.first < wanted; });
    if (found != std::end(kNames) && found->first == folded) {
        return std::string{found->second};
    }
    return std::string{text};
}

